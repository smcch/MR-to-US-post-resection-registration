def items(tex):
    bib = tex[tex.index(r"\begin{thebibliography}"):tex.index(r"\end{thebibliography}")]
    out = {}
    for it in re.split(r"(?=\\bibitem)", bib)[1:]:
        out[re.search(r"\]\{(\w+)\}", it).group(1)] = it.strip()
    return out


def cited(tex):
    keys = []
    for grp in re.findall(r"\\cite[a-z]*\{([^}]*)\}", tex):
        keys += [k.strip() for k in grp.split(",")]
    return sorted(set(keys))


def write(name, keys, pool, header):
    order = sorted(set(keys), key=lambda k: (re.sub(r"\d+\w?$", "", k).lower(), k))
    missing = [k for k in order if k not in pool]
    assert not missing, missing
    (OUT / name).write_text("\n".join([header, r"\begin{thebibliography}{00}"] + [pool[k] for k in order]
                                      + [r"\end{thebibliography}", ""]), encoding="utf-8")
    print(name, len(order), "entries")


